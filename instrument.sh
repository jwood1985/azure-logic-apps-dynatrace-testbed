#!/usr/bin/env bash
#
# instrument.sh — deploy the Dynatrace OneAgent site extension onto Logic App
#                 Standard (Windows) targets, with persistent state + resume.
#
# Per app: validate (Standard+Windows) → set DT_* app settings → ARM-deploy the
# `Dynatrace` site extension → restart → verify (ARM + Kudu).
#
# STATE / RESUME
#   Progress is appended to out/state.tsv (survives crashes). On re-run, apps
#   already "succeeded" are SKIPPED automatically — so re-running the same command
#   after a failure resumes where it left off (no needless restarts).
#     --force          re-instrument every target, ignoring prior state
#     --retry-failed   only re-attempt targets whose last state was a failure
#   A run lock (flock on out/.instrument.lock) prevents concurrent runs.
#
# SELECTION
#   --all                      every eligible target in out/targets.json
#   --name <app> [--rg <rg>]   one app
#   --subscription <name|id>   subscription for --name (else from manifest/AZ_SUBSCRIPTION)
#   Filters for --all (env): APP_NAME_FILTER (glob), RG_FILTER (comma list)
#
# OTHER
#   --dry-run       validate + print plan, change nothing
#   --drive-load    after instrument, ping the app to generate monitored load
#   --parallel N    instrument N apps concurrently (default 1)
#
# COMPLETION
#   A run only reports "succeeded" once the OneAgent binary is actually
#   installed (Kudu /dynatrace/api/status -> state=Installed,
#   isAgentInstalled=true). ARM "Succeeded" alone just means the extension
#   RESOURCE exists while the agent is still downloading.
#   Tune the wait with AGENT_WAIT_TRIES (default 40) x AGENT_WAIT_SLEEP (15s).
#
# CONCURRENCY NOTES
#   Safe to run N apps in parallel: state appends are flock-serialized, the
#   generated template is per-process, per-app artifacts are name-keyed, and
#   ARM deployment names are unique per app. Output is buffered per app and
#   printed atomically. A global run lock still prevents two separate
#   invocations from racing.
#   CAUTION: apps sharing one App Service Plan share Kudu/SCM compute, and
#   concurrent site-extension installs on the same plan can contend on file
#   locks. Prefer --parallel 1 within a plan, or parallelize across plans.
#
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$ROOT/out"; mkdir -p "$OUT"
TEMPLATE=""                        # set below: generated by default, or TEMPLATE_OVERRIDE
EXT_NAME="Dynatrace"
STATE="$OUT/state.tsv"            # persistent, append-only (last line per app wins)

[ -f "$ROOT/config.env" ] && { set +u; . "$ROOT/config.env"; set -u; }

# ---- args -------------------------------------------------------------------
MODE="" ; NAME="" ; RG="" ; SUB="${AZ_SUBSCRIPTION:-}" ; DRY=0 ; DRIVE=0 ; FORCE=0 ; RETRY_FAILED=0
PARALLEL="${PARALLEL:-1}"
APP_NAME_FILTER="${APP_NAME_FILTER:-}" ; RG_FILTER="${RG_FILTER:-}"
while [ $# -gt 0 ]; do
  case "$1" in
    --all)          MODE="all" ;;
    --name)         MODE="one"; NAME="${2:-}"; shift ;;
    --rg)           RG="${2:-}"; shift ;;
    --subscription) SUB="${2:-}"; shift ;;
    --dry-run)      DRY=1 ;;
    --drive-load)   DRIVE=1 ;;
    --force)        FORCE=1 ;;
    --retry-failed) RETRY_FAILED=1 ;;
    --parallel)     PARALLEL="${2:-1}"; shift ;;
    -h|--help)      grep '^#' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
  shift
done

fail(){ echo "ERROR: $*" >&2; exit 1; }
[ -n "$MODE" ] || fail "specify --all or --name <logicapp>"
# ---- template ---------------------------------------------------------------
# The site-extension template is tiny and never varies, so it is GENERATED here
# rather than read from disk. That removes a whole class of failures (missing,
# truncated, or swapped template files) — notably Dynatrace's published
# FULL-STACK template, which declares Microsoft.Web/serverfarms + a full
# Microsoft.Web/sites resource and, against an existing Logic App, can move it
# onto a new default-B1 plan and REPLACE its entire appSettings array.
#
# Advanced override: TEMPLATE=/path/to/custom.json (validated below).
if [ -n "${TEMPLATE_OVERRIDE:-}" ]; then
  TEMPLATE="$TEMPLATE_OVERRIDE"
  [ -f "$TEMPLATE" ] || fail "TEMPLATE_OVERRIDE points at a missing file: $TEMPLATE"
  if grep -qiE '"type"[[:space:]]*:[[:space:]]*"Microsoft\.Web/serverfarms"' "$TEMPLATE"; then
    fail "$TEMPLATE declares Microsoft.Web/serverfarms — that is the FULL-STACK template, not a site-extension template.
       Against an existing Logic App it can move the app to a new App Service plan and overwrite its app settings. Aborting."
  fi
  grep -q "logicAppName" "$TEMPLATE" || fail "$TEMPLATE does not define the 'logicAppName' parameter this tool passes."
else
  # Per-process filename: safe if several runs/workers share $OUT.
  TEMPLATE="$OUT/.siteextension.$$.json"
  cat > "$TEMPLATE" <<'ARMJSON'
{
  "$schema": "https://schema.management.azure.com/schemas/2019-04-01/deploymentTemplate.json#",
  "contentVersion": "1.0.0.0",
  "parameters": {
    "logicAppName": {
      "type": "string",
      "metadata": { "description": "Name of the existing Logic App (Standard) resource." }
    }
  },
  "resources": [
    {
      "type": "Microsoft.Web/sites/siteextensions",
      "apiVersion": "2022-09-01",
      "name": "[concat(parameters('logicAppName'), '/Dynatrace')]"
    }
  ],
  "outputs": {}
}
ARMJSON
fi
if [ "$DRY" -eq 0 ]; then
  : "${DT_TENANT:?set DT_TENANT (source config.env)}"
  : "${DT_API_TOKEN:?set DT_API_TOKEN (source config.env)}"
  case "$DT_TENANT$DT_API_TOKEN" in *REPLACE_ME*)
    fail "config.env still has REPLACE_ME placeholders — edit DT_TENANT and DT_API_TOKEN with your real values first" ;;
  esac
fi
DT_SSL_MODE="${DT_SSL_MODE:-default}"
DT_MONITORED_CLR="${DT_MONITORED_CLR:-both}"
command -v az >/dev/null || fail "az CLI not found"
az account show >/dev/null 2>&1 || fail "not logged in: run 'az login'"

# Validate the subscription up front — a bogus value (e.g. a partial name) makes
# every az call fail and would otherwise be misreported as "site not found".
if [ -n "$SUB" ]; then
  az account show --subscription "$SUB" --query id -o tsv >/dev/null 2>&1 || \
    fail "cannot resolve subscription '$SUB' (from --subscription/AZ_SUBSCRIPTION/config.env). Use the full subscription name or ID, or leave AZ_SUBSCRIPTION blank. 'az account list -o table' shows what you can access."
fi

# ---- run lock (prevent concurrent runs) -------------------------------------
LOCK="$OUT/.instrument.lock"
exec 9>"$LOCK" || true
if command -v flock >/dev/null 2>&1; then
  flock -n 9 || fail "another instrument.sh run holds the lock ($LOCK). Wait for it or remove the file if stale."
fi

# ---- persistent state (append-only; last line per app wins) -----------------
touch "$STATE"
state_status(){ awk -F'\t' -v n="$1" '$1==n{s=$4} END{print s}' "$STATE" 2>/dev/null; }
# Appends are serialized with flock so parallel workers can't interleave a line.
state_set(){ # name rg sub status detail
  local line
  line=$(printf '%s\t%s\t%s\t%s\t%s\t%s' "$1" "$2" "$3" "$4" "$5" "$(date -u +%FT%TZ)")
  ( flock 8; printf '%s\n' "$line" >> "$STATE" ) 8>"$OUT/.state.lock"
}

# ---- build the work list ----------------------------------------------------
declare -a TARGETS=()
if [ "$MODE" = "all" ]; then
  [ -f "$OUT/targets.json" ] || fail "no manifest — run ./discover.sh first"
  while IFS= read -r line; do TARGETS+=("$line"); done < <(python3 - "$OUT/targets.json" "$APP_NAME_FILTER" "$RG_FILTER" <<'PY'
import json,sys,fnmatch
rows=json.load(open(sys.argv[1]))
glob=sys.argv[2].strip(); rgs=[x.strip() for x in sys.argv[3].split(',') if x.strip()]
for r in rows:
    if not r.get("eligible"): continue
    if glob and not fnmatch.fnmatch(r["name"], glob): continue
    if rgs and r["resourceGroup"] not in rgs: continue
    print("%s|%s|%s" % (r["name"], r["resourceGroup"], r["subscriptionId"]))
PY
)
  [ ${#TARGETS[@]} -gt 0 ] || fail "no eligible targets after filters (manifest/APP_NAME_FILTER/RG_FILTER)"
else
  [ -n "$NAME" ] || fail "--name requires a value"
  if [ -z "$RG" ] && [ -f "$OUT/targets.json" ]; then
    RESOLVED=$(python3 - "$OUT/targets.json" "$NAME" <<'PY'
import json,sys
for r in json.load(open(sys.argv[1])):
    if r["name"]==sys.argv[2]: print("%s|%s"%(r["resourceGroup"],r["subscriptionId"]));break
PY
)
    RG="${RESOLVED%%|*}"; [ -z "$SUB" ] && SUB="${RESOLVED##*|}"
  fi
  [ -n "$RG" ] || fail "could not resolve resource group for '$NAME' — pass --rg"
  TARGETS+=("$NAME|$RG|${SUB}")
fi

echo "==> ${#TARGETS[@]} candidate target(s); dry-run=$DRY force=$FORCE retry-failed=$RETRY_FAILED drive-load=$DRIVE parallel=$PARALLEL"
if [ "$PARALLEL" -gt 1 ]; then
  # Same-plan concurrency can contend on Kudu file locks during extension install.
  PLANS=$(printf '%s\n' "${TARGETS[@]}" | cut -d'|' -f2 | sort -u | wc -l)
  echo "    NOTE: parallel mode — apps sharing an App Service Plan can contend on Kudu"
  echo "          file locks during install. Use --parallel 1 if you see failures."
fi
echo "    script:     ${BASH_SOURCE[0]}"
if [ -n "$SUB" ]; then
  echo "    subscription: $SUB (explicit)"
else
  echo "    subscription: $(az account show --query 'name' -o tsv 2>/dev/null) / $(az account show --query id -o tsv 2>/dev/null) (az DEFAULT — pass --subscription or set AZ_SUBSCRIPTION to override)"
fi
echo "    state file: $STATE"
echo

# ---- per-target instrumentation ---------------------------------------------
instrument_one(){
  local name="$1" rg="$2" sub="$3"
  local sub_args=(); [ -n "$sub" ] && sub_args=(--subscription "$sub")
  local status="unknown" detail=""

  echo "------------------------------------------------------------"
  echo ">> $name  (rg=$rg sub=${sub:-current})"

  local kind reserved state
  kind=$(az resource show "${sub_args[@]}" -g "$rg" -n "$name" \
          --resource-type Microsoft.Web/sites --query kind -o tsv 2>/dev/null || true)
  if [ -z "$kind" ]; then
    # Diagnose instead of a bare "not found": wrong subscription, Consumption
    # flavor, or a name typo all land here and need different fixes.
    local cur_sub; cur_sub=$(az account show "${sub_args[@]}" --query "[name,id]" -o tsv 2>/dev/null | paste -sd' | ' -)
    echo "   !! site not found via ARM (searched subscription: ${cur_sub:-unknown})"
    if ! az group show "${sub_args[@]}" -n "$rg" >/dev/null 2>&1; then
      echo "      -> resource group '$rg' does not exist in that subscription."
      echo "         Wrong subscription? Pass --subscription <name|id> (or set AZ_SUBSCRIPTION in config.env)."
      echo "         'az account list -o table' shows your subscriptions."
      state_set "$name" "$rg" "$sub" "not_found_rg" ""; return
    fi
    if az resource show "${sub_args[@]}" -g "$rg" -n "$name" --resource-type Microsoft.Logic/workflows >/dev/null 2>&1; then
      echo "      -> '$name' exists but is a CONSUMPTION Logic App (Microsoft.Logic/workflows)."
      echo "         Consumption has no Kudu/site extensions — the OneAgent site extension cannot be installed."
      echo "         Only Logic App STANDARD (Microsoft.Web/sites, Windows) is instrumentable this way."
      state_set "$name" "$rg" "$sub" "skip_consumption" ""; return
    fi
    echo "      -> RG exists but has no site named '$name'. Check the exact name:"
    echo "         az resource list -g $rg --query \"[?contains(type,'Web/sites') || contains(type,'Logic')].{name:name,type:type}\" -o table"
    state_set "$name" "$rg" "$sub" "not_found" ""; return; fi
  reserved=$(az webapp show "${sub_args[@]}" -g "$rg" -n "$name" --query reserved -o tsv 2>/dev/null || true)
  state=$(az webapp show "${sub_args[@]}" -g "$rg" -n "$name" --query state -o tsv 2>/dev/null || true)
  echo "   kind=$kind os=$([ "$reserved" = "true" ] && echo Linux || echo Windows) state=$state"

  case "$kind" in *workflowapp*) : ;; *) echo "   !! not a Logic App Standard — skipping"; state_set "$name" "$rg" "$sub" "skip_not_standard" "$kind"; return ;; esac
  if [ "$reserved" = "true" ]; then
    echo "   !! Linux Logic App — no Kudu/site extensions. skipping"; state_set "$name" "$rg" "$sub" "skip_linux" ""; return; fi

  if [ "$DRY" -eq 1 ]; then
    echo "   [dry-run] would set DT_* app settings, ARM-deploy '$EXT_NAME', restart, verify"
    state_set "$name" "$rg" "$sub" "dry_run" ""; return; fi

  echo "   [1/4] setting DT_* app settings"
  if ! az webapp config appsettings set "${sub_args[@]}" -g "$rg" -n "$name" --settings \
        DT_TENANT="$DT_TENANT" DT_API_TOKEN="$DT_API_TOKEN" \
        DT_SSL_MODE="$DT_SSL_MODE" DT_MONITORED_CLR="$DT_MONITORED_CLR" \
        --output none 2>"$OUT/$name.appsettings.err"; then
    echo "   !! app settings failed: $(tr '\n' ' ' <"$OUT/$name.appsettings.err")"
    state_set "$name" "$rg" "$sub" "appsettings_failed" ""; return; fi

  echo "   [2/4] deploying site extension via ARM template"
  if ! az deployment group create "${sub_args[@]}" \
        --resource-group "$rg" --name "dynatrace-oneagent-siteextension-$name" \
        --template-file "$TEMPLATE" --parameters logicAppName="$name" \
        --output json >"$OUT/$name.deployment.json" 2>"$OUT/$name.deployment.err"; then
    echo "   !! deployment failed: $(tr '\n' ' ' <"$OUT/$name.deployment.err" | head -c 400)"
    state_set "$name" "$rg" "$sub" "deployment_failed" ""; return; fi
  local prov
  prov=$(python3 -c "import json;print(json.load(open('$OUT/$name.deployment.json'))['properties']['provisioningState'])" 2>/dev/null || echo "?")
  echo "        deployment provisioningState=$prov"

  echo "   [3/5] restarting app"
  az webapp restart "${sub_args[@]}" -g "$rg" -n "$name" --output none 2>/dev/null || echo "        (restart non-zero — continuing)"

  echo "   [4/5] verifying site extension resource (ARM)"
  local sub_id; sub_id=$(az account show "${sub_args[@]}" --query id -o tsv 2>/dev/null)
  local ext_url="/subscriptions/${sub_id}/resourceGroups/${rg}/providers/Microsoft.Web/sites/${name}/siteextensions/${EXT_NAME}?api-version=2023-01-01"
  local ext_json ext_state
  ext_json=$(az rest --method GET --url "$ext_url" 2>/dev/null || true)
  ext_state=$(printf '%s' "$ext_json" | grep -oP '"provisioningState"\s*:\s*"\K[^"]+' | head -1 || true)
  [ -z "$ext_state" ] && ext_state="$prov"
  echo "        extension resource state=$ext_state"

  # [5/5] ARM "Succeeded" only means the extension RESOURCE exists. The OneAgent
  # binary is downloaded/installed asynchronously afterwards (Kudu shows
  # "Downloading the agent… N%"). Poll the extension's own status endpoint until
  # the agent is really installed before declaring success.
  echo "   [5/5] waiting for OneAgent download/install to finish (Kudu)"
  local host scm tok kudu_code agent_state agent_installed agent_ver
  host=$(az webapp show "${sub_args[@]}" -g "$rg" -n "$name" --query defaultHostName -o tsv 2>/dev/null)
  scm="https://${host/.azurewebsites.net/.scm.azurewebsites.net}"
  tok=$(az account get-access-token "${sub_args[@]}" --resource "https://management.azure.com" --query accessToken -o tsv 2>/dev/null | tr -d '\r')
  agent_state=""; agent_installed=""; agent_ver=""
  local tries="${AGENT_WAIT_TRIES:-40}" nap="${AGENT_WAIT_SLEEP:-15}" i
  for i in $(seq 1 "$tries"); do
    kudu_code=$(curl -s -o "$OUT/$name.kudu.json" -w '%{http_code}' --max-time 25 \
                 -H "Authorization: Bearer $tok" "$scm/dynatrace/api/status" 2>/dev/null || echo 000)
    if [ "$kudu_code" = "200" ]; then
      read -r agent_state agent_installed agent_ver < <(python3 -c "
import json
try:
    d=json.load(open('$OUT/$name.kudu.json'))
    print(d.get('state','?'), d.get('isAgentInstalled',False), d.get('version','?'))
except Exception: print('? False ?')" 2>/dev/null)
      if [ "$agent_state" = "Installed" ] && [ "$agent_installed" = "True" ]; then
        echo "        agent INSTALLED (version $agent_ver) after $((i*nap))s"; break
      fi
      echo "        agent state=$agent_state installed=$agent_installed (${i}/${tries}, $((i*nap))s elapsed)"
    elif [ "$kudu_code" = "403" ]; then
      echo "        Kudu 403 (SCM network-blocked) — cannot confirm agent install; relying on ARM state"
      agent_state="kudu_blocked"; break
    elif [ "$i" -eq 1 ]; then
      echo "        Kudu HTTP $kudu_code (app may still be restarting) — retrying"
    fi
    sleep "$nap"
  done

  if [ "$agent_state" = "Installed" ] && [ "$agent_installed" = "True" ]; then
    echo "   [OK] $name fully instrumented (agent $agent_ver, extension=$ext_state)"
    status="succeeded"; detail="agent $agent_ver"
  elif [ "$agent_state" = "kudu_blocked" ]; then
    if [ "$ext_state" = "Succeeded" ]; then
      echo "   [~] $name extension deployed but agent install UNVERIFIED (Kudu blocked)"
      status="succeeded_unverified"; detail="$ext_state/kudu_blocked"
    else
      status="verify_uncertain"; detail="$ext_state/kudu_blocked"
    fi
  elif [ "$ext_state" = "Succeeded" ]; then
    echo "   [!] $name: extension deployed but agent still '$agent_state' after $((tries*nap))s"
    echo "       Not fatal — the download can continue. Re-run ./verify.sh later, or raise AGENT_WAIT_TRIES."
    status="agent_install_timeout"; detail="state=$agent_state"
  else
    echo "   ? $name: extension state=$ext_state (see $OUT/$name.deployment.json)"
    status="verify_uncertain"; detail="$ext_state"
  fi

  if [ "$DRIVE" -eq 1 ]; then
    local host; host=$(az webapp show "${sub_args[@]}" -g "$rg" -n "$name" --query defaultHostName -o tsv 2>/dev/null || true)
    if [ -n "$host" ]; then
      echo "   [load] pinging https://$host (10x)"
      for i in $(seq 1 10); do curl -s -o /dev/null -w "        hit %{http_code}\n" --max-time 20 "https://$host/" || true; sleep 1; done
    fi
  fi
  state_set "$name" "$rg" "$sub" "$status" "$detail"
}

# ---- main loop with resume/skip (optionally parallel) -----------------------
# In parallel mode each worker buffers its output to a per-app log and prints it
# atomically (flock) when done, so apps' output never interleaves.
run_job(){
  local n="$1" r="$2" s="$3"
  if [ "$PARALLEL" -le 1 ]; then
    instrument_one "$n" "$r" "$s"
  else
    local log="$OUT/$n.run.log"
    instrument_one "$n" "$r" "$s" >"$log" 2>&1
    ( flock 7; cat "$log" ) 7>"$OUT/.print.lock"
  fi
}

declare -a RAN=()
running=0
for t in "${TARGETS[@]}"; do
  IFS='|' read -r n r s <<<"$t"
  st="$(state_status "$n")"
  if [ "$FORCE" -eq 0 ] && [ "$st" = "succeeded" ]; then
    echo ">> $n — already succeeded (skip; use --force to redo)"; continue
  fi
  if [ "$RETRY_FAILED" -eq 1 ]; then
    case "$st" in
      ""|succeeded|skip_*|dry_run) echo ">> $n — retry-failed: last='${st:-none}', skipping"; continue ;;
    esac
  fi
  if [ "$PARALLEL" -le 1 ]; then
    run_job "$n" "$r" "$s"
  else
    run_job "$n" "$r" "$s" &
    running=$((running+1))
    if [ "$running" -ge "$PARALLEL" ]; then
      wait -n 2>/dev/null || wait
      running=$((running-1))
    fi
  fi
  RAN+=("$n")
done
[ "$PARALLEL" -gt 1 ] && wait

# ---- summary (from persistent state, for this run's candidates) -------------
echo
echo "============================ SUMMARY ============================"
python3 - "$STATE" "$(printf '%s\n' "${TARGETS[@]}")" <<'PY'
import sys
state={}
for ln in open(sys.argv[1]):
    p=ln.rstrip("\n").split("\t")
    if len(p)>=4: state[p[0]]=(p[3], p[4] if len(p)>4 else "")
cands=[l.split("|")[0] for l in sys.argv[2].splitlines() if l.strip()]
w=max((len(c) for c in cands), default=4)
ok=0
for c in cands:
    stt,det=state.get(c,("(not run)",""))
    if stt=="succeeded": ok+=1
    print(f"  {c.ljust(w)}  {stt}" + (f"  ({det})" if det else ""))
print(f"\n  {ok}/{len(cands)} succeeded (cumulative, from state)")
PY
echo "  state: $STATE   (persists across runs; re-run to resume, --force to redo)"
